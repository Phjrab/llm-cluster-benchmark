#!/usr/bin/env python3
"""Create plots for medical benchmark summaries.

This script reads the medical comparison CSV and renders a compact chart with
model accuracy plus a stacked count view of correct answers vs. reasoning
failures.
"""

from __future__ import annotations

import argparse
import csv
import math
import os
from typing import Dict, List, Optional


MODEL_NAME_MAP = {
    "llama3_2_1b": "Llama-3.2-1B",
    "llama3_2_3b": "Llama-3.2-3B",
    "llama3_8b": "Llama-3-8B",
    "qwen2_5_1_5b": "Qwen2.5-1.5B",
    "qwen2_5_3b": "Qwen2.5-3B",
    "deepseek_r1_1_5b": "DeepSeek-R1-1.5B",
    "deepseek_r1_7b": "DeepSeek-R1-7B",
    "gemma2_2b": "Gemma2-2B",
    "phi3_mini": "Phi-3-Mini",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Plot medical benchmark results.")
    parser.add_argument(
        "--summary-csv",
        default=None,
        help="Input CSV generated by compare_medical_models.py",
    )
    parser.add_argument(
        "--output-png",
        default=None,
        help="Output image path",
    )
    parser.add_argument(
        "--output-dir",
        default="outputs/medical_benchmark",
        help="Directory used when output paths are not provided",
    )
    parser.add_argument("--dpi", type=int, default=170, help="PNG DPI")
    parser.add_argument(
        "--sort-by",
        default="accuracy",
        choices=["accuracy", "correct_answers", "reasoning_failure_count", "total_questions"],
        help="Column used for sorting models",
    )
    return parser.parse_args()


def _to_float(value: Optional[str], fallback: float = 0.0) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return fallback


def _to_int(value: Optional[str], fallback: int = 0) -> int:
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return fallback


def short_model_name(raw_name: object) -> str:
    name = str(raw_name or "unknown")
    normalized = name.lower().replace("-", "_").replace(".", "_")
    for prefix, short_name in MODEL_NAME_MAP.items():
        if normalized.startswith(prefix):
            return short_name
    return name


def load_rows(csv_path: str) -> List[Dict[str, str]]:
    if not os.path.isfile(csv_path):
        raise FileNotFoundError(f"CSV not found: {csv_path}")

    with open(csv_path, "r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        rows = list(reader)

    if not rows:
        raise ValueError("CSV is empty.")

    return rows


def sort_rows(rows: List[Dict[str, str]], sort_by: str) -> List[Dict[str, str]]:
    if sort_by == "accuracy":
        return sorted(
            rows,
            key=lambda row: (
                -_to_float(row.get("accuracy")),
                -_to_int(row.get("correct_answers")),
                row.get("model_name", ""),
            ),
        )

    reverse = sort_by != "reasoning_failure_count"
    return sorted(rows, key=lambda row: _to_float(row.get(sort_by)), reverse=reverse)


def apply_short_names(rows: List[Dict[str, str]]) -> List[Dict[str, str]]:
    enriched: List[Dict[str, str]] = []
    for row in rows:
        updated = dict(row)
        updated["short_name"] = short_model_name(row.get("model_name", row.get("name", "unknown")))
        enriched.append(updated)
    return enriched


def render_plot(rows: List[Dict[str, str]], output_png: str, dpi: int) -> None:
    try:
        import matplotlib.pyplot as plt
    except ImportError as exc:
        raise RuntimeError("matplotlib is not installed. Run: pip install matplotlib") from exc

    names = [row.get("short_name") or short_model_name(row.get("model_name", "unknown")) for row in rows]
    accuracy = [_to_float(row.get("accuracy")) for row in rows]
    correct = [_to_int(row.get("correct_answers")) for row in rows]
    failures = [
        _to_int(row.get("reasoning_failure_count"), max(0, _to_int(row.get("total_questions")) - _to_int(row.get("correct_answers"))))
        for row in rows
    ]
    totals = [_to_int(row.get("total_questions"), max(c + f, 0)) for row, c, f in zip(rows, correct, failures)]

    fig, axes = plt.subplots(2, 1, figsize=(max(10, 1.5 * len(rows)), 8.2), sharex=True)
    fig.suptitle("Medical Benchmark Comparison", fontsize=15, fontweight="bold")

    accuracy_color = "#2f6f8f"
    correct_color = "#3a8f6b"
    failure_color = "#b55252"

    axes[0].bar(names, accuracy, color=accuracy_color)
    axes[0].set_ylabel("Accuracy (%)")
    axes[0].set_ylim(0, 100 if not accuracy else min(100, max(100, max(accuracy) + 5)))
    axes[0].grid(axis="y", alpha=0.25)
    axes[0].set_title("Model Accuracy")
    for idx, value in enumerate(accuracy):
        axes[0].text(idx, value + 1.5, f"{value:.1f}%", ha="center", va="bottom", fontsize=9)

    axes[1].bar(names, correct, color=correct_color, label="Correct")
    axes[1].bar(names, failures, bottom=correct, color=failure_color, label="Failures")
    axes[1].set_ylabel("Questions")
    axes[1].set_title("Correct Answers vs. Reasoning Failures")
    axes[1].grid(axis="y", alpha=0.25)
    axes[1].legend(frameon=False, ncol=2, loc="upper right")
    axes[1].set_ylim(0, max(totals) + 1 if totals else 1)

    for idx, (c_count, f_count, total) in enumerate(zip(correct, failures, totals)):
        axes[1].text(idx, c_count / 2 if c_count else 0.15, str(c_count), ha="center", va="center", color="white", fontsize=9, fontweight="bold")
        if f_count > 0:
            axes[1].text(idx, c_count + (f_count / 2), str(f_count), ha="center", va="center", color="white", fontsize=9, fontweight="bold")
        axes[1].text(idx, total + 0.15, str(total), ha="center", va="bottom", fontsize=8)

    axes[1].tick_params(axis="x", labelrotation=20)
    plt.tight_layout(rect=[0, 0, 1, 0.96])
    plt.savefig(output_png, dpi=dpi)
    plt.close(fig)


def main() -> int:
    args = parse_args()
    summary_csv = args.summary_csv or os.path.join(args.output_dir, "medical_compare_summary.csv")
    output_png = args.output_png or os.path.join(args.output_dir, "medical_compare.png")

    os.makedirs(os.path.dirname(output_png), exist_ok=True)

    rows = load_rows(summary_csv)
    rows = apply_short_names(sort_rows(rows, args.sort_by))
    render_plot(rows, output_png, args.dpi)

    print(f"Saved plot: {output_png}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())