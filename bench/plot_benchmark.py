def plot_metric_overview(rows: List[Dict[str, str]], output_png: Path, dpi: int, sort_by: str) -> bool:
    if not rows:
        warn("No rows available for overview plot")
        return False

    plt = ensure_matplotlib()
    sorted_rows = apply_short_names(sort_rows(rows, sort_by))
    metrics = select_metrics(sorted_rows)
    names = [display_name(row) for row in sorted_rows]

    ncols = 3
    nrows = max(1, math.ceil(len(metrics) / ncols))
    fig, axes = plt.subplots(nrows, ncols, figsize=(5 * ncols, 3.8 * nrows))
    fig.suptitle("Local LLM Comparison (Jetson Orin Nano)", fontsize=15, fontweight="bold")

    axes_flat = axes.flatten() if hasattr(axes, "flatten") else [axes]
    bar_color = "#2f6f8f"

    for idx, spec in enumerate(metrics):
        ax = axes_flat[idx]
        key = str(spec["key"])
        values = [safe_float(row.get(key, 0.0)) for row in sorted_rows]
        ax.bar(names, values, color=bar_color)
        ax.set_title(str(spec["title"]))
        ax.set_ylabel(str(spec["ylabel"]))
        ax.tick_params(axis="x", labelrotation=20)
        ax.grid(axis="y", alpha=0.25)

    for idx in range(len(metrics), len(axes_flat)):
        axes_flat[idx].set_visible(False)

    plt.tight_layout(rect=[0, 0, 1, 0.96])
    save_figure(fig, output_png, dpi)
    plt.close(fig)
    return True


def plot_core_comparison(rows: List[Dict[str, str]], output_png: Path, dpi: int) -> bool:
    if not rows:
        warn("No successful rows available for core comparison plot")
        return False

    plt = ensure_matplotlib()
    plot_rows = apply_short_names(sort_rows(normalize_numeric_rows(rows, ["avg_tps", "avg_ttft_s", "peak_process_rss_mb", "avg_power_w"]), "avg_tps"))
    names = [display_name(row) for row in plot_rows]
    avg_tps = [safe_float(row.get("avg_tps"), 0.0) for row in plot_rows]
    avg_ttft = [safe_float(row.get("avg_ttft_s"), 0.0) for row in plot_rows]
    peak_rss = [safe_float(row.get("peak_process_rss_mb"), 0.0) for row in plot_rows]
    avg_power = [safe_float(row.get("avg_power_w"), 0.0) for row in plot_rows]

    fig, axes = plt.subplots(2, 2, figsize=(16, 11))
    fig.suptitle("Jetson Local LLM Benchmark - Core Comparison", fontsize=15, fontweight="bold")

    axes[0, 0].bar(names, avg_tps, color="#2c7fb8")
    axes[0, 0].set_title("Average TPS by Model")
    axes[0, 0].set_ylabel("tokens/s")
    axes[0, 0].tick_params(axis="x", rotation=35)
    axes[0, 0].grid(axis="y", alpha=0.25)

    axes[0, 1].plot(names, avg_ttft, marker="o", color="#d95f0e")
    axes[0, 1].set_title("Average TTFT by Model")
    axes[0, 1].set_ylabel("seconds")
    axes[0, 1].tick_params(axis="x", rotation=35)
    axes[0, 1].grid(axis="y", alpha=0.25)

    box_data: List[List[float]] = []
    box_labels: List[str] = []
    for label, values in [
        ("avg_tps", avg_tps),
        ("avg_ttft_s", avg_ttft),
        ("peak_process_rss_mb", peak_rss),
        ("avg_power_w", avg_power),
    ]:
        filtered = [value for value in values if value is not None]
        if filtered:
            box_data.append(filtered)
            box_labels.append(label)

    if box_data:
        axes[1, 0].boxplot(box_data, tick_labels=box_labels, showmeans=True)
        axes[1, 0].set_title("Metric Distribution Across Models")
        axes[1, 0].tick_params(axis="x", rotation=20)
        axes[1, 0].grid(axis="y", alpha=0.25)
    else:
        axes[1, 0].text(0.5, 0.5, "No data for box plot", ha="center", va="center")
        axes[1, 0].set_axis_off()

    scale_rows = []
    for row in plot_rows:
        model_size_b = parse_model_size_b(str(row.get("name", "")))
        if not math.isnan(model_size_b) and safe_float(row.get("avg_tps"), 0.0) > 0:
            scale_rows.append((model_size_b, safe_float(row.get("avg_tps"), 0.0), display_name(row)))

    if scale_rows:
        scale_rows.sort(key=lambda item: item[0])
        axes[1, 1].plot([item[0] for item in scale_rows], [item[1] for item in scale_rows], marker="o", color="#31a354")
        for size_b, tps, name in scale_rows:
            axes[1, 1].annotate(name, (size_b, tps), fontsize=8)
        axes[1, 1].set_title("Scaling: Model Size (B) vs TPS")
        axes[1, 1].set_xlabel("Model size (B)")
        axes[1, 1].set_ylabel("tokens/s")
        axes[1, 1].grid(alpha=0.25)
    else:
        axes[1, 1].text(0.5, 0.5, "No parseable model size data", ha="center", va="center")
        axes[1, 1].set_axis_off()

    plt.tight_layout(rect=[0, 0, 1, 0.96])
    save_figure(fig, output_png, dpi)
    plt.close(fig)
    return True


def plot_efficiency(rows: List[Dict[str, str]], output_png: Path, dpi: int) -> bool:
    if not rows:
        warn("Skipping efficiency plot because no successful rows were found")
        return False

    plt = ensure_matplotlib()
    efficiency_rows: List[Dict[str, object]] = []
    for row in rows:
        avg_power_w = optional_float(row.get("avg_power_w"))
        avg_tps = optional_float(row.get("avg_tps"))
        if avg_power_w is None or avg_power_w <= 0 or avg_tps is None:
            continue
        efficiency_rows.append({"name": short_model_name(row.get("name", row.get("model_name", "unknown"))), "tps_per_w": avg_tps / avg_power_w})

    if not efficiency_rows:
        warn("Skipping efficiency plot because avg_power_w is unavailable")
        return False

    efficiency_rows.sort(key=lambda row: safe_float(row.get("tps_per_w"), 0.0), reverse=True)
    names = [str(row["name"]) for row in efficiency_rows]
    tps_per_w = [safe_float(row.get("tps_per_w"), 0.0) for row in efficiency_rows]

    fig, ax = plt.subplots(1, 1, figsize=(10, 5))
    fig.suptitle("Jetson Benchmark - Efficiency", fontsize=14, fontweight="bold")

    ax.bar(names, tps_per_w, color="#238b45")
    ax.set_title("Efficiency (TPS/W)")
    ax.set_ylabel("tokens/s/W")
    ax.tick_params(axis="x", rotation=35)
    ax.grid(axis="y", alpha=0.25)

    plt.tight_layout(rect=[0, 0, 1, 0.92])
    save_figure(fig, output_png, dpi)
    plt.close(fig)
    return True


def plot_power_thermal_dashboard(rows: List[Dict[str, str]], output_png: Path, dpi: int) -> bool:
    required_columns = {"avg_power_w", "peak_gpu_temp_c", "avg_tps"}
    if not rows:
        warn("Skipping power/thermal dashboard because no successful rows were found")
        return False
    if not required_columns.issubset(set(rows[0].keys()) | set().union(*(row.keys() for row in rows))):
        warn("Skipping power/thermal dashboard because required columns are unavailable")
        return False

    plt = ensure_matplotlib()
    normalized = apply_short_names(normalize_numeric_rows(rows, ["avg_power_w", "peak_gpu_temp_c", "avg_tps"]))

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    fig.suptitle("Jetson Benchmark - Power/Thermal Dashboard", fontsize=14, fontweight="bold")

    power_points = []
    temp_points = []
    for row in normalized:
        avg_power_w = optional_float(row.get("avg_power_w"))
        peak_gpu_temp_c = optional_float(row.get("peak_gpu_temp_c"))
        avg_tps = optional_float(row.get("avg_tps"))
        name = display_name(row)
        if avg_power_w is not None and avg_tps is not None:
            power_points.append((avg_power_w, avg_tps, name))
        if peak_gpu_temp_c is not None and avg_tps is not None:
            temp_points.append((peak_gpu_temp_c, avg_tps, name))

    axes[0].scatter([item[0] for item in power_points], [item[1] for item in power_points], c="#1f78b4", s=65)
    for x, y, name in power_points:
        axes[0].annotate(name, (x, y), fontsize=8)
    axes[0].set_title("Power vs Throughput")
    axes[0].set_xlabel("avg_power_w")
    axes[0].set_ylabel("avg_tps")
    axes[0].grid(alpha=0.25)

    axes[1].scatter([item[0] for item in temp_points], [item[1] for item in temp_points], c="#e6550d", s=65)
    for x, y, name in temp_points:
        axes[1].annotate(name, (x, y), fontsize=8)
    axes[1].set_title("GPU Temp vs Throughput")
    axes[1].set_xlabel("peak_gpu_temp_c")
    axes[1].set_ylabel("avg_tps")
    axes[1].grid(alpha=0.25)

    plt.tight_layout(rect=[0, 0, 1, 0.92])
    save_figure(fig, output_png, dpi)
    plt.close(fig)
    return True


def plot_report_card(rows: List[Dict[str, str]], output_png: Path, dpi: int) -> bool:
    if not rows:
        warn("Skipping report card because no successful rows were found")
        return False

    plt = ensure_matplotlib()
    report_rows = apply_short_names(sort_rows(normalize_numeric_rows(rows, ["avg_tps", "avg_ttft_s", "peak_process_rss_mb"]), "avg_tps"))
    if not report_rows:
        warn("Skipping report card because avg_tps is unavailable")
        return False

    best_tps = report_rows[0]
    ttft_candidates = [row for row in report_rows if optional_float(row.get("avg_ttft_s")) is not None]
    rss_candidates = [row for row in report_rows if optional_float(row.get("peak_process_rss_mb")) is not None]
    best_ttft = min(ttft_candidates, key=lambda row: safe_float(row.get("avg_ttft_s"), float("inf"))) if ttft_candidates else best_tps
    lowest_rss = min(rss_candidates, key=lambda row: safe_float(row.get("peak_process_rss_mb"), float("inf"))) if rss_candidates else best_tps

    fig = plt.figure(figsize=(14, 8))
    grid = fig.add_gridspec(2, 2, height_ratios=[1, 2])

    ax_text = fig.add_subplot(grid[0, :])
    ax_text.axis("off")
    header = [
        "Jetson Local LLM Benchmark - Report Card",
        f"Best TPS: {display_name(best_tps)} ({safe_float(best_tps.get('avg_tps'), 0.0):.2f} tok/s)",
        f"Best TTFT: {display_name(best_ttft)} ({safe_float(best_ttft.get('avg_ttft_s'), 0.0):.3f} s)",
        f"Lowest RSS: {display_name(lowest_rss)} ({safe_float(lowest_rss.get('peak_process_rss_mb'), 0.0):.1f} MB)",
    ]
    ax_text.text(0.01, 0.9, "\n".join(header), fontsize=14, va="top")

    ax_tps = fig.add_subplot(grid[1, 0])
    ax_ttft = fig.add_subplot(grid[1, 1])

    top_rows = report_rows[:6]
    ax_tps.barh([display_name(row) for row in reversed(top_rows)], [safe_float(row.get("avg_tps"), 0.0) for row in reversed(top_rows)], color="#2c7fb8")
    ax_tps.set_title("Top TPS")
    ax_tps.set_xlabel("tokens/s")
    ax_tps.grid(axis="x", alpha=0.25)

    ttft_rows = [row for row in top_rows if optional_float(row.get("avg_ttft_s")) is not None]
    ttft_rows = sorted(ttft_rows, key=lambda row: safe_float(row.get("avg_ttft_s"), float("inf")))
    ax_ttft.barh([display_name(row) for row in ttft_rows], [safe_float(row.get("avg_ttft_s"), 0.0) for row in ttft_rows], color="#d95f0e")
    ax_ttft.set_title("Top Latency (Lower Better)")
    ax_ttft.set_xlabel("seconds")
    ax_ttft.grid(axis="x", alpha=0.25)

    plt.tight_layout()
    save_figure(fig, output_png, dpi)
    plt.close(fig)
    return True


def copy_ranked_csv(ranked_csv: Path, output_path: Path) -> bool:
    if not ranked_csv.is_file():
        warn(f"Ranked CSV not found: {ranked_csv}")
        return False

    output_path.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ranked_csv, output_path)
    return True


def main() -> int:
    args = parse_args()

    input_csv = Path(args.input_csv)
    ranked_csv = Path(args.ranked_csv)
    output_dir = Path(args.output_dir)
    os.makedirs(output_dir, exist_ok=True)

    paths = build_paths(output_dir)
    rows = read_success_rows(input_csv)
    if rows is None:
        warn("No benchmark data available; skipping plot generation")
        return 0

    rows = apply_short_names(rows)

    summary_rows = build_summary_rows(rows)
    failed_rows = build_failed_rows(read_csv_rows(input_csv) or [])

    if summary_rows:
        save_csv_rows(paths.summary_csv, summary_rows, SUMMARY_COLUMNS)
        info(f"Saved summary table: {paths.summary_csv}")

    if failed_rows:
        save_csv_rows(paths.failed_csv, failed_rows)
        info(f"Saved failed model table: {paths.failed_csv}")

    if ranked_csv.is_file():
        if copy_ranked_csv(ranked_csv, paths.ranked_csv):
            info(f"Saved ranked table copy: {paths.ranked_csv}")

    overview_saved = plot_metric_overview(rows, paths.overview_png, args.dpi, args.sort_by)
    core_saved = plot_core_comparison(rows, paths.core_png, args.dpi)
    efficiency_saved = plot_efficiency(rows, paths.efficiency_png, args.dpi)
    power_saved = plot_power_thermal_dashboard(rows, paths.power_gpu_png, args.dpi)
    report_saved = plot_report_card(rows, paths.report_png, args.dpi)

    info(f"Saved plot directory: {paths.output_dir}")
    if overview_saved:
        info(f"Saved overview plot: {paths.overview_png}")
    if core_saved:
        info(f"Saved core comparison plot: {paths.core_png}")
    if efficiency_saved:
        info(f"Saved efficiency plot: {paths.efficiency_png}")
    if power_saved:
        info(f"Saved power/thermal dashboard: {paths.power_gpu_png}")
    if report_saved:
        info(f"Saved report card: {paths.report_png}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
