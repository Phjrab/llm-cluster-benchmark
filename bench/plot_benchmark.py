def warn(message: str) -> None:
    print(f"[WARN] {message}")


def info(message: str) -> None:
    print(f"[INFO] {message}")


def safe_float(value: object, fallback: float = 0.0) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return fallback


def optional_float(value: object) -> Optional[float]:
    if value is None:
        return None
    if isinstance(value, str) and not value.strip():
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def short_model_name(raw_name: object) -> str:
    """Convert long raw model names into compact chart labels."""

    name = str(raw_name or "unknown")
    normalized = name.lower().replace("-", "_").replace(".", "_")
    for prefix, short_name in MODEL_NAME_MAP.items():
        if normalized.startswith(prefix):
            return short_name
    return name


def apply_short_names(rows: Sequence[Dict[str, str]]) -> List[Dict[str, str]]:
    enriched: List[Dict[str, str]] = []
    for row in rows:
        updated = dict(row)
        display_name = row.get("name") or row.get("model_name") or "unknown"
        updated["short_name"] = short_model_name(display_name)
        enriched.append(updated)
    return enriched


def ensure_matplotlib():
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError as exc:  # pragma: no cover
        raise RuntimeError("matplotlib is not installed. Run: pip install matplotlib") from exc

    return plt


def read_csv_rows(csv_path: Path) -> Optional[List[Dict[str, str]]]:
    if not csv_path.is_file():
        warn(f"CSV not found: {csv_path}")
        return None

    try:
        with csv_path.open("r", encoding="utf-8", newline="") as handle:
            reader = csv.DictReader(handle)
            rows = list(reader)
    except Exception as exc:
        warn(f"Failed to read {csv_path}: {exc}")
        return None

    if not rows:
        warn(f"CSV is empty: {csv_path}")
        return None

    return rows


def read_success_rows(csv_path: Path) -> Optional[List[Dict[str, str]]]:
    rows = read_csv_rows(csv_path)
    if rows is None:
        return None

    if any("status" in row for row in rows):
        rows = [row for row in rows if row.get("status") == "ok"]

    if not rows:
        warn(f"No successful rows found in {csv_path}")
        return None

    return rows


def sort_rows(rows: List[Dict[str, str]], sort_by: str) -> List[Dict[str, str]]:
    reverse = METRIC_BY_KEY[sort_by]["higher_is_better"]
    return sorted(rows, key=lambda row: safe_float(row.get(sort_by, 0.0)), reverse=reverse)


def select_metrics(rows: List[Dict[str, str]]) -> List[Dict[str, object]]:
    selected: List[Dict[str, object]] = []
    for spec in METRIC_SPECS:
        if spec["always_show"]:
            selected.append(spec)
            continue

        key = str(spec["key"])
        has_any = any(optional_float(row.get(key)) is not None for row in rows)
        if has_any:
            selected.append(spec)
    return selected


def normalize_numeric_rows(rows: Sequence[Dict[str, str]], columns: Sequence[str]) -> List[Dict[str, object]]:
    normalized: List[Dict[str, object]] = []
    for row in rows:
        normalized_row: Dict[str, object] = dict(row)
        for column in columns:
            if column in normalized_row:
                normalized_row[column] = optional_float(normalized_row[column])
        normalized.append(normalized_row)
    return normalized


def display_name(row: Dict[str, object]) -> str:
    return str(row.get("short_name") or row.get("name") or row.get("model_name") or "unknown")


def save_csv_rows(path: Path, rows: Sequence[Dict[str, object]], fieldnames: Optional[Sequence[str]] = None) -> None:
    if not rows:
        return

    path.parent.mkdir(parents=True, exist_ok=True)
    if fieldnames is None:
        fieldnames = list(rows[0].keys())

    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(fieldnames))
        writer.writeheader()
        for row in rows:
            writer.writerow({key: row.get(key, "") for key in fieldnames})


def save_figure(fig, output_path: Path, dpi: int) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=dpi, bbox_inches="tight")


def parse_model_size_b(name: str) -> float:
    match = re.search(r"(\d+(?:_\d+)?)b", name.lower())
    if not match:
        return float("nan")
    return float(match.group(1).replace("_", "."))


def build_summary_rows(rows: Sequence[Dict[str, str]]) -> List[Dict[str, object]]:
    normalized = normalize_numeric_rows(rows, NUMERIC_COLUMNS)
    if not normalized:
        return []

    sortable = [row for row in normalized if optional_float(row.get("avg_tps")) is not None]
    if not sortable:
        return []

    baseline_row = max(sortable, key=lambda row: safe_float(row.get("avg_tps"), 0.0))
    baseline_tps = safe_float(baseline_row.get("avg_tps"), 0.0)
    baseline_ttft = optional_float(baseline_row.get("avg_ttft_s"))

    summary_rows: List[Dict[str, object]] = []
    for row in sortable:
        summary_row: Dict[str, object] = {
            "name": row.get("name", "unknown"),
            "short_name": short_model_name(row.get("name", row.get("model_name", "unknown"))),
            "avg_tps": row.get("avg_tps", ""),
            "avg_ttft_s": row.get("avg_ttft_s", ""),
            "peak_process_rss_mb": row.get("peak_process_rss_mb", ""),
            "avg_power_w": row.get("avg_power_w", ""),
            "peak_gpu_temp_c": row.get("peak_gpu_temp_c", ""),
        }
        if baseline_tps > 0:
            summary_row["tps_rel_to_baseline"] = safe_float(row.get("avg_tps"), 0.0) / baseline_tps
        else:
            summary_row["tps_rel_to_baseline"] = ""

        if baseline_ttft not in (None, 0.0):
            current_ttft = optional_float(row.get("avg_ttft_s"))
            if current_ttft is not None:
                summary_row["ttft_delta_pct_vs_baseline"] = ((current_ttft - baseline_ttft) / baseline_ttft) * 100.0
            else:
                summary_row["ttft_delta_pct_vs_baseline"] = ""
        summary_rows.append(summary_row)

    summary_rows.sort(key=lambda row: safe_float(row.get("avg_tps"), 0.0), reverse=True)
    return summary_rows


def build_failed_rows(rows: Sequence[Dict[str, str]]) -> List[Dict[str, str]]:
    if not rows or not any("status" in row for row in rows):
        return []
    return [dict(row) for row in rows if row.get("status") != "ok"]


